namespace StudioFourteen.Reshade;

using StudioFourteen.Panels;
using System.Windows;

public partial class NotSupportedPanel : Panel
{
	public int ReShadeVersionPacked { get; set; }

	protected override void OnClosed()
	{
		if (this.DontNotifyCheckbox.IsChecked == true)
			this.Services.Settings.Current.HasConfirmedReShadeVersion = this.ReShadeVersionPacked;

		base.OnClosed();
	}

	private void OnConfirmClicked(object sender, RoutedEventArgs e)
	{
		this.Close();
	}
}