namespace StudioFourteen.Interop.Structs;

using System.Runtime.InteropServices;

[StructLayout(LayoutKind.Explicit)]
public unsafe struct CharacterBaseScale
{
	[FieldOffset(0x2A0)] public float ScaleFactor1;
	[FieldOffset(0x2A4)] public float ScaleFactor2;

	public readonly float ScaleFactor => this.ScaleFactor1 * this.ScaleFactor2;
}