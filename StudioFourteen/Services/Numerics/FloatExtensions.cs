namespace StudioFourteen.Services.Numerics;

using System;

public static class FloatExtensions
{
	public static bool IsApproximately(this float a, float b, float delta = float.Epsilon)
	{
		float dX = MathF.Abs(a - b);
		return dX <= delta;
	}
}
