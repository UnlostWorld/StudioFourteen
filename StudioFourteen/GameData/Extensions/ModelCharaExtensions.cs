namespace Lumina.Excel.Sheets;

using StudioFourteen.Tags;

public static class ModelCharaExtensions
{
	public static TagCollection? ToTags(this ModelChara modelChara)
	{
		TagCollection tags = new();

		if (modelChara.RowId == 0)
		{
			tags.Add("Humanoid");
		}
		else
		{
			tags.Add("Monster");
		}

		return tags;
	}
}
