namespace StudioFourteen;

using System;

[AttributeUsage(AttributeTargets.Property | AttributeTargets.Class)]
public class InspectAttribute : Attribute
{
	public readonly string? Path;

	public InspectAttribute()
	{
	}

	public InspectAttribute(string path)
	{
		this.Path = path;
	}
}

[AttributeUsage(AttributeTargets.Property)]
public class InspectPageAttribute : Attribute
{
	public readonly string? Path;

	public InspectPageAttribute(string path)
	{
		this.Path = path;
	}
}