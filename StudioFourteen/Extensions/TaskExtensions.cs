namespace System.Threading.Tasks;

using StudioFourteen;

public static class TaskExtensions
{
	public static void RunAsynchronously(this Task task)
	{
		task.ContinueWith(HandleTaskException, TaskContinuationOptions.OnlyOnFaulted);
	}

	private static void HandleTaskException(Task task, object? arg2)
	{
		if (task.Exception == null)
			return;

		Studio.Log.Error(task.Exception, "Exception in task");
	}
}