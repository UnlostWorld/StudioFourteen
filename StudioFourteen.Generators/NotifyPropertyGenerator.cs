namespace StudioFourteen.Generators;

using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;
using System.Text;

[Generator(LanguageNames.CSharp)]
public class NotifyPropertyChangedGenerator : IIncrementalGenerator
{
	public void Initialize(IncrementalGeneratorInitializationContext context)
	{
		SourceText attributeDefinition = SourceText.From($$"""
			// <auto-generated/>
			namespace StudioFourteen;
			[System.AttributeUsage(System.AttributeTargets.Class)]
			public class NotifyPropertyChangedAttribute : System.Attribute
			{
			}
			""", Encoding.UTF8);

		context.RegisterPostInitializationOutput(ctx =>
		{
			ctx.AddSource($"StudioFourteen.NotifyPropertyChangedAttribute.g.cs", attributeDefinition);
		});

		IncrementalValuesProvider<ITypeSymbol> pipeline = context.SyntaxProvider.ForAttributeWithMetadataName(
			"StudioFourteen.NotifyPropertyChangedAttribute",
			(node, _) => true,
			(context, _) => (ITypeSymbol)context.TargetSymbol);

		context.RegisterSourceOutput(pipeline, this.Generate);
	}

	private void Generate(SourceProductionContext context, ITypeSymbol type)
	{
		string fileName = $"{type.Name}.g.cs";

		string namespaceStr = type.ContainingNamespace.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat.WithGlobalNamespaceStyle(SymbolDisplayGlobalNamespaceStyle.Omitted));

		SourceText source = SourceText.From($$"""
			// <auto-generated/>
			namespace {{namespaceStr}};
			using System.ComponentModel;
			using System.Runtime.CompilerServices;
			partial class {{type.Name}} : INotifyPropertyChanged
			{
				public event PropertyChangedEventHandler PropertyChanged;

				protected void NotifyPropertyChanged([CallerMemberName] string propertyName = "")
				{
					if (this.PropertyChanged != null)
					{
						this.PropertyChanged.Invoke(this, new(propertyName));
					}
				}
			}
			""",
			Encoding.UTF8);

		context.AddSource(fileName, source);
	}
}